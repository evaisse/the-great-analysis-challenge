#!/usr/bin/env python3
"""Generate src/pst.bend from the piece-square tables in AI_ALGORITHM_SPEC.md."""
import argparse
import re
from pathlib import Path

PIECES = [("pawn", "Pawn"), ("knight", "Knight"), ("bishop", "Bishop"),
          ("rook", "Rook"), ("queen", "Queen"), ("king", "King")]

HEADER = """# Piece-square tables from AI_ALGORITHM_SPEC.md (generated by
# tools/gen_pst.py), White's view, indexed by square (a1 = 0). Each table
# packs four entries per U32 word as bytes holding value + 50; a lookup
# walks the word index bit by bit.
import Base
import ./board.bend as B
"""


def table(spec: str, title: str) -> list[int]:
    section = spec[spec.index(f"#### {title} Table"):]
    rows = re.findall(r"^\d \[(.*?)\]", section, re.M)[:8]
    ranks = [[int(x) for x in row.split(",")] for row in rows]
    return [v for row in reversed(ranks) for v in row]


def tree(words: list[int], lo: int, hi: int, bit: int) -> str:
    if hi - lo == 1:
        return str(words[lo])
    mid = (lo + hi) // 2
    return (f"B.sel(B.bit(w, {1 << bit}), {tree(words, mid, hi, bit - 1)}, "
            f"{tree(words, lo, mid, bit - 1)})")


def generate(spec: str) -> str:
    out = [HEADER]
    for name, title in PIECES:
        vals = table(spec, title)
        words = [sum((vals[4 * k + j] + 50) << (8 * j) for j in range(4)) for k in range(16)]
        out.append(f"def pst.{name}(+i: U32) -> U32:\n"
                   f"  +w = U32.shrn(i, 2n)\n"
                   f"  +word = {tree(words, 0, 16, 3)}\n"
                   "  U32.sub(U32.and(U32.shrn(word, U32.to_nat(U32.shln(U32.and(i, 3), 3n))), 255), 50)\n")
    calls = [f"pst.{n}(i)" for n, _ in PIECES]
    out.append("# the bonus of piece type t (1..6) at index i\n"
               "def pst(+t: U32, +i: U32) -> U32:\n"
               f"  B.sel(B.eq(t, 1), {calls[0]}, B.sel(B.eq(t, 2), {calls[1]}, B.sel(B.eq(t, 3), {calls[2]},\n"
               f"    B.sel(B.eq(t, 4), {calls[3]}, B.sel(B.eq(t, 5), {calls[4]}, {calls[5]})))))\n")
    return "\n".join(out)


def main() -> None:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="cmd", required=True)
    for cmd in ("write", "check"):
        p = sub.add_parser(cmd, help=f"{cmd} src/pst.bend")
        p.add_argument("--spec", type=Path, default=here.parents[2] / "AI_ALGORITHM_SPEC.md")
        p.add_argument("--out", type=Path, default=here.parent / "src" / "pst.bend")
    args = parser.parse_args()
    text = generate(args.spec.read_text())
    if args.cmd == "write":
        args.out.write_text(text)
    elif args.out.read_text() != text:
        raise SystemExit(f"{args.out} is stale: run tools/gen_pst.py write")


if __name__ == "__main__":
    main()
